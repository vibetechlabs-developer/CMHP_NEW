export function getCoaDetailsByBatch(batchNo) {
  if (!batchNo) return null
  return COA_CATALOG_DATA[batchNo] || null
}

export function getDosageFormClass(form) {
  const norm = String(form || '').trim().toLowerCase()
  if (norm.includes('syrup')) return 'dosage-syrup'
  if (norm.includes('drop')) return 'dosage-drops'
  if (norm.includes('liquid')) return 'dosage-liquid'
  if (norm.includes('tincture') || norm.includes('mother')) return 'dosage-mother-tincture'
  if (norm.includes('oil')) return 'dosage-oil'
  if (norm.includes('tablet')) return 'dosage-tablet'
  if (norm.includes('capsule')) return 'dosage-capsule'
  if (norm.includes('kit')) return 'dosage-kits'
  if (norm.includes('pill')) return 'dosage-pills'
  return 'dosage-default'
}

